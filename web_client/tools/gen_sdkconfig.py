#!/usr/bin/env python3
"""Generate sdkconfig.h for the web client from the firmware's Kconfig.

Usage: gen_sdkconfig.py <firmware dir> <out sdkconfig.h> <defaults file>...

Evaluates web_client/tools/Kconfig.web (which sources the firmware's
Kconfig.projbuild files) with kconfiglib, applies the defaults
files in order (web_client/sdkconfig.defaults, then firmware/
sdkconfig.defaults.lang_all, as idf.py --lang-pack
does), and writes the C header the sources include
as "sdkconfig.h". Symbols the Kconfig files do not declare (TinyUSB,
power management, ...) are ignored: the web client has no such hardware.
"""
import os
import sys

import kconfiglib


def main():
    if len(sys.argv) < 4:
        sys.exit(__doc__)
    firmware, out = sys.argv[1:3]
    defaults = sys.argv[3:]
    os.environ["DRAFTLING_FIRMWARE"] = os.path.abspath(firmware)
    here = os.path.dirname(os.path.abspath(__file__))
    kconf = kconfiglib.Kconfig(os.path.join(here, "Kconfig.web"),
                               warn_to_stderr=False)
    for i, path in enumerate(defaults):
        kconf.load_config(path, replace=(i == 0))
    tmp = out + ".tmp"
    kconf.write_autoconf(tmp, header="/* Generated by web_client/tools/"
                                     "gen_sdkconfig.py -- do not edit. */\n")
    # Only touch the file when it changes, so make does not rebuild
    # everything on every run.
    old = None
    if os.path.exists(out):
        with open(out) as f:
            old = f.read()
    with open(tmp) as f:
        new = f.read()
    if new != old:
        os.replace(tmp, out)
    else:
        os.remove(tmp)


if __name__ == "__main__":
    main()
