#!/usr/bin/env python3
"""Write an assembler file embedding binary files like ESP-IDF's EMBED_FILES.

Usage: gen_embed.py <out.S> <file>...

For each file, defines _binary_<name>_start and _binary_<name>_end,
<name> being the file's base name with every character that is not a
letter or digit replaced by '_' -- the symbols the firmware's fonts and
input methods (cjk_font.c, tamil_font.c, indic_font.c, ime_builtin.c)
declare. The data is pulled in with .incbin, which Emscripten's
assembler supports.
"""
import os
import re
import sys


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    out = sys.argv[1]
    lines = ["/* Generated by online_demo/tools/gen_embed.py -- do not edit. */"]
    for path in sys.argv[2:]:
        name = re.sub(r"[^A-Za-z0-9]", "_", os.path.basename(path))
        size = os.path.getsize(path)
        sym = "_binary_" + name
        lines += [
            '  .section .rodata.%s,"",@' % sym,
            "  .globl %s_start" % sym,
            "  .globl %s_end" % sym,
            "  .p2align 2",
            "%s_start:" % sym,
            '  .incbin "%s"' % os.path.abspath(path),
            "%s_end:" % sym,
            "  .int8 0",
            "  .size %s_start, %d" % (sym, size + 1),
            "  .size %s_end, 1" % sym,
        ]
    tmp = out + ".tmp"
    with open(tmp, "w") as f:
        f.write("\n".join(lines) + "\n")
    os.replace(tmp, out)


if __name__ == "__main__":
    main()
