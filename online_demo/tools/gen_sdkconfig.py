#!/usr/bin/env python3
"""Generate sdkconfig.h for the online demo from the firmware's Kconfig.

Usage: gen_sdkconfig.py <firmware dir> <board defaults file> <out sdkconfig.h>

Evaluates online_demo/tools/Kconfig.demo (which sources the firmware's
Kconfig.projbuild files) with kconfiglib, applies the board's
sdkconfig.defaults.<board>, and writes the C header the sources include
as "sdkconfig.h". Symbols the Kconfig files do not declare (TinyUSB,
power management, ...) are ignored: the demo has no such hardware.
"""
import os
import sys

import kconfiglib


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    firmware, defaults, out = sys.argv[1:]
    os.environ["DRAFTLING_FIRMWARE"] = os.path.abspath(firmware)
    here = os.path.dirname(os.path.abspath(__file__))
    kconf = kconfiglib.Kconfig(os.path.join(here, "Kconfig.demo"),
                               warn_to_stderr=False)
    kconf.load_config(defaults, replace=True)
    tmp = out + ".tmp"
    kconf.write_autoconf(tmp, header="/* Generated by online_demo/tools/"
                                     "gen_sdkconfig.py -- do not edit. */\n")
    # Only touch the file when it changes, so make does not rebuild
    # everything on every run.
    old = None
    if os.path.exists(out):
        with open(out) as f:
            old = f.read()
    with open(tmp) as f:
        new = f.read()
    if new != old:
        os.replace(tmp, out)
    else:
        os.remove(tmp)


if __name__ == "__main__":
    main()
